    def _inspect(self, question: str) -> dict:
        return inspect_repository(
            "https://github.com/example/checkout-service",
            "sample",
            str(self.root),
            question,
            protected_root=PROJECT_ROOT.parent,
        )

    def _load_scenarios(self) -> list[dict]:
        with open(self.benchmark_path, encoding="utf-8") as fh:
            return json.load(fh)

    def test_impact_question_scenario_must_be_rejected(self) -> None:
        """
        CURRENTLY FAILS: the benchmark has no scenario for change-impact questions.
        A correctly scoped benchmark must include such a scenario and expect
        UNSUPPORTED_QUESTION. Adding one here proves v1 cannot satisfy it.

        This test acts as the missing scenario and shows v1 behavior is behind
        the benchmark's implied contract: the benchmark must grow to include
        unsupported-question coverage, and v1 must implement the rejection.
        """
        # This scenario SHOULD be in scenarios.json to protect the product boundary
        adversarial_scenario = {
            "id": "change-impact-unsupported",
            "question": "What is the impact of changing the checkout event bus?",
            "expected": {"error_code": "UNSUPPORTED_QUESTION"},
        }

        with self.assertRaises(InspectionError) as caught:
            self._inspect(adversarial_scenario["question"])
        self.assertEqual(
            caught.exception.code,
            adversarial_scenario["expected"]["error_code"],
            msg=(
                f"Scenario {adversarial_scenario['id']!r}: expected "
                f"UNSUPPORTED_QUESTION for a change-impact question, "
                f"but v1 accepted it and returned a report. "
                f"The benchmark must include this scenario and v1 must implement the rejection."
            ),
        )

    def test_all_existing_benchmark_scenarios_pass(self) -> None:
        """
        Acts as the missing benchmark runner. Validates all scenarios in
        scenarios.json against the current fixture. Any failure here means
        benchmark expectations diverge from v1 behavior.

        If this test itself passes, the runner infrastructure was missing but the
        scenarios happened to be aligned. If it fails, it identifies which
        scenario is 'ahead of v1'.
        """
        scenarios = self._load_scenarios()
        failures: list[str] = []

        for scenario in scenarios:
            sid = scenario["id"]
            question = scenario["question"]
            expected = scenario["expected"]

            try:
                if "error_code" in expected:
                    try:
                        self._inspect(question)
                        failures.append(
                            f"{sid}: expected error {expected['error_code']!r} but call succeeded"
                        )
                    except InspectionError as exc:
                        if str(exc.code) != str(expected["error_code"]):
                            failures.append(
                                f"{sid}: expected error {expected['error_code']!r} "
                                f"but got {exc.code!r}"
                            )
                    continue

                report = self._inspect(question)
                all_text = json.dumps(report)

                if "must_cite" in expected:
                    cited_paths = {item["path"] for item in report["evidence"]}
                    if expected["must_cite"] not in cited_paths:
                        failures.append(
                            f"{sid}: must_cite {expected['must_cite']!r} not in evidence paths "
                            f"{sorted(cited_paths)!r}"
                        )

                if expected.get("must_not_be_unknown"):
                    rationale_unknowns = [
                        f for f in report["findings"]["unknown"]
                        if "rationale" in f["statement"].casefold()
                    ]
                    if rationale_unknowns:
                        failures.append(
                            f"{sid}: must_not_be_unknown violated; "
                            f"has {len(rationale_unknowns)} unknown-rationale finding(s)"
                        )

                if expected.get("must_report_unknown_rationale"):
                    has_unknown = any(
                        "rationale" in f["statement"].casefold()
                        for f in report["findings"]["unknown"]
                    )
                    if not has_unknown:
                        failures.append(
                            f"{sid}: expected unknown-rationale finding but none present"
                        )

                if "must_include_any" in expected:
                    found = any(
                        s.casefold() in all_text.casefold()
                        for s in expected["must_include_any"]
                    )
                    if not found:
                        failures.append(
                            f"{sid}: must_include_any {expected['must_include_any']!r} "
                            f"— none of these strings appear in the JSON report"
                        )

            except InspectionError as exc:
                if "error_code" not in expected:
                    failures.append(
                        f"{sid}: unexpected InspectionError {exc.code!r}: {exc.message}"
                    )
            except Exception as exc:
                failures.append(f"{sid}: unexpected {type(exc).__name__}: {exc}")

        self.assertFalse(
            failures,
            msg="Benchmark scenario failures:\n" + "\n".join(f"  - {f}" for f in failures),
        )


